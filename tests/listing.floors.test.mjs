// Разбор этажа и этажности из текста поста (api/_listingFacts.js → extractFloorInfo).
// Запуск: node --test tests/listing.floors.test.mjs  (или npm run test:seo)

import { test } from "node:test";
import assert from "node:assert/strict";
import { extractFloorInfo } from "../api/_listingFacts.js";

const toNum = (v) => (v === "" || v == null ? null : Number(v));

// [текст, этаж, этажность]
const CASES = [
    ["Этаж: 5/9", 5, 9], ["5/9 этаж", 5, 9], ["Этаж 5 из 9", 5, 9], ["5 этаж из 9", 5, 9], ["5-й этаж 9-этажного дома", 5, 9],
    ["Этаж: 5 (из 9)", 5, 9], ["Этаж - 5; этажность - 12", 5, 12], ["Этажность: 12, этаж: 7", 7, 12], ["эт. 5/9", 5, 9], ["5/9 эт.", 5, 9],
    ["3/5/9 кирпичный дом", 5, 9], ["2/4/9, евро", 4, 9], ["Продам 3к 5/9", 5, 9], ["3-комн. 7/16, 90 м2", 7, 16], ["1/4 этаж", 1, 4],
    ["На 5 этаже девятиэтажного дома", 5, 9], ["пятый этаж из девяти", 5, 9], ["5 этаж, 9 этажность", 5, 9], ["Этаж: 12/16", 12, 16],
    ["Qavat: 5/9", 5, 9], ["5-qavat, 9 qavatli uy", 5, 9], ["Floor 5 of 9", 5, 9], ["5th floor", 5, null], ["Этаж 3-4", 3, null],
    ["Этаж: 1", 1, null], ["Этаж 16 из 16", 16, 16], ["10 этаж 12 этажного", 10, 12], ["Этажей в доме: 12, этаж 3", 3, 12],
    ["Этаж: 8, этажей: 16", 8, 16], ["5 из 9 этаж", 5, 9], ["площадь 68 м2, этаж 5/9, ремонт", 5, 9],
    ["Квартира 68м², 5/9, евроремонт", 5, 9], ["Этаж: пятый", 5, null], ["9-этажный дом", null, 9],
    ["Дом 9 этажей, квартира на 5-м", 5, 9], ["этаж 5 /9", 5, 9], ["этаж 5 / 9", 5, 9], ["Этаж:5/9", 5, 9], ["5-этаж", 5, null],
    ["5 этаж 9-этажный", 5, 9], ["5 этаж из 9-ти", 5, 9], ["этаж: 5; всего этажей: 9", 5, 9], ["Этажность 9", null, 9],
    ["12/12 этаж", 12, 12], ["1/1 этаж", 1, 1], ["Этаж 2/2", 2, 2], ["Продаётся 2 комнатная квартира, 4/5 этаж", 4, 5],
    ["🏠 Продаётся 3к квартира\n📍 Яккасарайский район\n🏢 Этаж: 5/9\n📐 68 м²\n💰 95 000$", 5, 9],
    ["Сдаю 1к, 2 этаж 5-этажного дома, 450$", 2, 5],
    ["Продаётся: 3 комнаты, этаж 7, этажность 12, площадь 90 м2", 7, 12],
];

test("этаж и этажность берутся из разных форматов записи", () => {
    for (const [text, floor, total] of CASES) {
        const r = extractFloorInfo(text);
        assert.equal(toNum(r.floor), floor, `этаж: ${JSON.stringify(text)} -> ${r.floor}`);
        assert.equal(toNum(r.totalFloors), total, `этажность: ${JSON.stringify(text)} -> ${r.totalFloors}`);
    }
});

test("площадь, цена, телефон, даты и доли не принимаются за этаж", () => {
    const NONE = [
        "Площадь 68/45/10 м2", "Цена 95000$, торг 1/2", "Тел: +998 90 123 45 67", "Работаем 24/7", "Продаётся 1/2 доли дома",
        "Дата 12/10/2026", "5 комнат, 68 м2", "Кухня 12 м, ванная 4 м", "Цена 450 у.е. за 1 м2",
        "Потолки 2.8 м, площадь 45/60 м2", "Участок 6 соток, дом 120/80 м2", "1/2 комнаты в общежитии", "3к 68 м2 евроремонт",
    ];
    for (const text of NONE) {
        const r = extractFloorInfo(text);
        assert.equal(r.floor, "", `ложный этаж: ${JSON.stringify(text)} -> ${r.floor}`);
        assert.equal(r.totalFloors, "", `ложная этажность: ${JSON.stringify(text)} -> ${r.totalFloors}`);
    }
});

test("этаж выше этажности — этажность отбрасывается", () => {
    const r = extractFloorInfo("Этаж: 12, этажность: 9");
    assert.equal(r.floor, "12");
    assert.equal(r.totalFloors, "");
});
